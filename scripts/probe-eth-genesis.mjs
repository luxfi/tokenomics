// Probe Ethereum mainnet for the live state of the Genesis NFT Media contract
// and write data/eth-genesis-inventory.json. Read-only: eth_call / eth_getCode
// only — this script can never send a transaction.
//
//   node scripts/probe-eth-genesis.mjs            # write the inventory
//   node scripts/probe-eth-genesis.mjs --check    # verify chain still matches it
import { readFileSync, writeFileSync } from 'node:fs'

const MEDIA = '0x31e0F919C67ceDd2Bc3E294340Dc900735810311'
const RPCS = (process.env.ETH_RPC ? [process.env.ETH_RPC] : []).concat([
  'https://ethereum-rpc.publicnode.com', 'https://eth.drpc.org', 'https://eth.llamarpc.com',
])
let rr = 0
async function rpc(method, params) {
  let last
  for (let k = 0; k < RPCS.length * 3; k++) {
    const url = RPCS[rr++ % RPCS.length]
    try {
      const res = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }) })
      if (!res.ok) { last = new Error(`${url}: HTTP ${res.status}`); continue }
      const j = await res.json()
      if (j.error) throw new Error(`${method}: ${j.error.message}`)
      return j.result
    } catch (e) { last = e; if (/revert|execution/i.test(String(e.message))) throw e }
  }
  throw last
}
const pad = (h) => h.padStart(64, '0')
const u256 = (n) => pad(BigInt(n).toString(16))
const call = (data, to = MEDIA) => rpc('eth_call', [{ to, data }, 'latest'])
const num = (r) => Number(BigInt(r))
const str = (r) => {
  const h = r.replace(/^0x/, '')
  if (h.length < 128) return ''
  const len = parseInt(h.slice(64, 128), 16)
  return Buffer.from(h.slice(128, 128 + len * 2), 'hex').toString('utf8')
}
const addr = (r) => '0x' + r.replace(/^0x/, '').slice(24)

const total = num(await call('0x18160ddd'))                              // totalSupply()
const tokens = []
for (let i = 0; i < total; i++) {
  const id = num(await call('0x4f6ccce7' + u256(i)))                     // tokenByIndex(uint256)
  tokens.push({
    id, owner: addr(await call('0x6352211e' + u256(id))),                // ownerOf(uint256)
    uri: str(await call('0xc87b56dd' + u256(id))),                       // tokenURI(uint256)
    contentHash: await call('0xfad32197' + u256(id)),                    // tokenContentHashes(uint256)
  })
}
// Classification comes from the tokenURI itself — the only on-chain type signal.
const typeOf = (u) => (new URLSearchParams(u.slice(u.indexOf('?') + 1)).get('type') ?? '').replace(/_/g, '')
const luxOf = (u) => Number(new URLSearchParams(u.slice(u.indexOf('?') + 1)).get('lux') ?? 0)
for (const t of tokens) { t.type = typeOf(t.uri); t.bond = t.type === 'validator' ? 1_000_000_000 : luxOf(t.uri) }

const inv = {
  $comment: 'Live Ethereum mainnet state of the Genesis NFT Media contract. Generated by scripts/probe-eth-genesis.mjs.',
  chainId: 1, contract: MEDIA, name: str(await call('0x06fdde03')), symbol: str(await call('0x95d89b41')),
  owner: addr(await call('0x8da5cb5b')), block: num(await rpc('eth_blockNumber', [])),
  totalSupply: total, tokens,
}
const path = new URL('../data/eth-genesis-inventory.json', import.meta.url)

if (process.argv.includes('--check')) {
  const want = JSON.parse(readFileSync(path, 'utf8'))
  const norm = (o) => JSON.stringify({ ...o, block: 0 })
  if (norm(want) !== norm(inv)) { console.error('MISMATCH: chain state differs from data/eth-genesis-inventory.json'); process.exit(1) }
  console.log(`OK  chain matches inventory: ${total} tokens, ids ${tokens[0].id}..${tokens.at(-1).id}`)
} else {
  writeFileSync(path, JSON.stringify(inv, null, 2) + '\n')
  console.log(`wrote ${total} tokens (ids ${tokens[0].id}..${tokens.at(-1).id}) at block ${inv.block}`)
}
// Invariants that must hold for the collection to be sound.
const ids = tokens.map((t) => t.id).sort((a, b) => a - b)
const dup = ids.filter((v, i) => ids[i - 1] === v)
const gaps = ids.filter((v, i) => v !== i + 1)
const badURI = tokens.filter((t) => !/^https?:\/\/[^?]+\?.+/.test(t.uri))
const noHash = tokens.filter((t) => /^0x0*$/.test(t.contentHash))
console.log(`    duplicates=${dup.length} gaps=${gaps.length} malformedURIs=${badURI.length} zeroContentHash=${noHash.length}`)
if (dup.length || gaps.length || badURI.length) process.exit(1)
